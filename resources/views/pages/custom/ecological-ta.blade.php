            <p class="eyebrow">SPOTLIGHT INITIATIVE</p>
            <h2>Check economic migration along border areas</h2>
            <p>A unique vision of the Indian Army has entailed plantation of high-quality <strong>Walnut and Chilgoza saplings</strong> in the Malari region of Uttarakhand to prevent migration of villagers. Malari is strategically located in Niti Valley, on an axis leading to the China Border, and is remotely located — cut off from Joshimath due to heavy snowfall between December and April. Locals migrate to lower regions during this period, with no employment and inadequate cultivable land for a sustainable livelihood.</p>
            <p>The project was initiated on the directions of <strong>General Bipin Rawat, UYSM, AVSM, YSM, SM, VSM, ADC, Chief of the Army Staff</strong>, who conceived the idea.</p>
            <p>The uniqueness of the initiative is that it involves <strong>all resident families</strong> in planting saplings of Walnut and Chilgoza, which will belong to them. They are the sole beneficiaries of the fruit borne by their saplings.</p>
