            <p class="eyebrow">BACKGROUND</p>
            <h2>The story began in the Shivaliks</h2>
            <p>The early 1980s were a trying time for the fragile ecology of the Shivalik Ranges. Mussoorie was on the brink of losing its pristine splendour due to unscientific and illegal limestone mining, which intensified deforestation at an unprecedented rate.</p>
            <p>Alarmed at the ecological degradation in the Shivaliks, <strong>Dr Norman Borlough</strong>, from the Wheat and Maize Centre, Mexico, suggested to former Prime Minister <strong>Mrs. Indira Gandhi</strong> that the Indian Army be involved to restore the ecological balance on a war footing. As the Regular Army could not be used for the purpose, it was decided to raise a Territorial Army Unit, enrolling ex-servicemen from the region.</p>
            <p>The dual aim was <strong>re-settlement of Ex-Servicemen</strong> and <strong>regeneration of ecology</strong>. As a unique experiment, <strong>127 Infantry Battalion (Territorial Army) GARHWAL RIFLES</strong> was raised on <strong>01 December 1982</strong>.</p>
